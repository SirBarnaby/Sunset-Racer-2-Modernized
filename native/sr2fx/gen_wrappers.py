"""Generates wrappers_gen.h: pass-through classes for IDirect3D9 and
IDirect3DDevice9 from the Windows SDK's d3d9.h. Methods named in CUSTOM are
only declared; sr2fx.cpp implements them. Run: python gen_wrappers.py"""
import re, sys, pathlib

SDK = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\Include")
hdr = sorted(SDK.glob("*/shared/d3d9.h"))[-1].read_text()

CUSTOM = {
    "D3D9": {"QueryInterface", "AddRef", "Release", "CreateDevice"},
    "Device": {"QueryInterface", "AddRef", "Release", "GetDirect3D", "Reset", "Present",
               "BeginScene", "EndScene", "Clear", "SetTransform", "SetRenderTarget",
               "SetDepthStencilSurface", "GetRenderTarget", "GetDepthStencilSurface",
               "SetRenderState", "SetViewport", "SetLight", "DrawIndexedPrimitiveUP",
               "GetRenderTargetData", "SetFVF", "SetVertexShader"},
}

def methods(iface):
    body = re.search(r"DECLARE_INTERFACE_\(%s, IUnknown\)\s*\{(.*?)\n\};" % iface, hdr, re.S).group(1)
    out = []
    for m in re.finditer(r"STDMETHOD(_\(\s*([\w ]+?)\s*,\s*)?\(?(\w+)\)?\)\((THIS_?)\s*(.*?)\)\s*PURE;", body):
        ret = m.group(2) or "HRESULT"
        name = m.group(3)
        params = m.group(5).strip()
        if m.group(4) == "THIS":
            params = ""
        out.append((ret.strip(), name, params))
    return out

def argnames(params, name):
    if not params:
        return []
    names = []
    for i, p in enumerate(params.split(",")):
        p = p.strip()
        mm = re.search(r"(\w+)\s*$", p)
        tokens = re.findall(r"\w+", p)
        # an unnamed parameter (type only), e.g. MultiplyTransform(D3DTRANSFORMSTATETYPE,CONST D3DMATRIX*)
        if p.endswith("*") or len([t for t in tokens if t not in ("CONST", "const")]) < 2:
            names.append(None)
        else:
            names.append(mm.group(1))
    return names

def fix_params(params, name):
    if not params:
        return "", ""
    parts, call = [], []
    for i, (p, n) in enumerate(zip(params.split(","), argnames(params, name))):
        p = p.strip()
        if n is None:
            n = "a%d" % i
            p = p + " " + n
        parts.append(p)
        call.append(n)
    return ", ".join(parts), ", ".join(call)

def emit(cls, iface, real, key):
    lines = ["class %s : public %s {" % (cls, iface), "public:"]
    for ret, name, params in methods(iface):
        decl, call = fix_params(params, name)
        sig = "%s STDMETHODCALLTYPE %s(%s)" % (ret, name, decl)
        if name in CUSTOM[key]:
            lines.append("    %s override = 0;" % sig)
        else:
            r = "" if ret == "void" else "return "
            lines.append("    %s override { %s%s->%s(%s); }" % (sig, r, real, name, call))
    return lines

out = ["// Generated by gen_wrappers.py from the Windows SDK d3d9.h. Do not edit.",
       "#pragma once", "#include <d3d9.h>", "",
       "class ProxyDevice;", ""]
out += emit("ProxyD3D9Base", "IDirect3D9", "m_real", "D3D9")
out += ["protected:", "    IDirect3D9* m_real = nullptr;", "};", ""]
out += emit("ProxyDeviceBase", "IDirect3DDevice9", "m_real", "Device")
out += ["protected:", "    IDirect3DDevice9* m_real = nullptr;", "};", ""]
pathlib.Path(__file__).with_name("wrappers_gen.h").write_text("\n".join(out) + "\n")
print("wrote", len(methods("IDirect3D9")), "+", len(methods("IDirect3DDevice9")), "methods")
